"""Compact the d3-celestial datasets into src/data.js for Skylight.

Source: d3-celestial (BSD-3) data files — stars to mag 6 derived from the
HYG database (Hipparcos), constellation lines/names, star proper names,
bright DSOs, and the milky way outline.

Usage: python3 make_data.py <d3-celestial-package-data-dir>
"""
import json
import sys
import os

SRC = sys.argv[1] if len(sys.argv) > 1 else "package/data"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "data.js")


def load(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return json.load(f)


def ra_from_lon(lon):
    return round(lon % 360, 2)


# ---- stars ----
stars_json = load("stars.6.json")
names_json = load("starnames.json")

feats = sorted(stars_json["features"], key=lambda f: f["properties"]["mag"])
flat = []          # ra, dec, mag, bv flattened
name_map = {}      # star index -> proper name
info_map = {}      # star index -> [bayer/desig, constellation]
for i, f in enumerate(feats):
    lon, lat = f["geometry"]["coordinates"]
    mag = f["properties"]["mag"]
    try:
        bv = float(f["properties"].get("bv") or 0)
    except ValueError:
        bv = 0
    flat += [ra_from_lon(lon), round(lat, 2), round(mag, 1), round(bv, 1)]
    meta = names_json.get(str(f["id"]))
    if meta:
        if meta.get("name"):
            name_map[i] = meta["name"]
        if mag <= 3.6 and (meta.get("desig") or meta.get("c")):
            info_map[i] = [meta.get("desig", ""), meta.get("c", "")]

# ---- constellations ----
lines_json = load("constellations.lines.json")
cnames_json = load("constellations.json")
cmeta = {}
for f in cnames_json["features"]:
    lon, lat = f["geometry"]["coordinates"]
    cmeta[f["id"][:3]] = {"n": f["properties"]["en"], "p": [ra_from_lon(lon), round(lat, 1)],
                          "r": int(f["properties"].get("rank", "3"))}

cons = []
for f in lines_json["features"]:
    cid = f["id"][:3]
    segs = []
    for seg in f["geometry"]["coordinates"]:
        pts = []
        for lon, lat in seg:
            pts += [ra_from_lon(lon), round(lat, 1)]
        segs.append(pts)
    m = cmeta.get(cid, {"n": cid, "p": [0, 0], "r": 3})
    cons.append({"c": cid, "n": m["n"], "p": m["p"], "r": m["r"], "s": segs})

# ---- bright DSOs ----
dsos_json = load("dsos.bright.json")
dnames = load("dsonames.json")
dsos = []
for f in dsos_json["features"]:
    if f["id"] == "GC":  # galactic center marker, skip
        continue
    lon, lat = f["geometry"]["coordinates"]
    nm = dnames.get(f["id"], {}).get("name") or f["id"]
    dsos.append([ra_from_lon(lon), round(lat, 2), f["properties"]["mag"], nm,
                 f["properties"]["type"]])
# M13 — the Hercules cluster deserves a spot
dsos.append([250.42, 36.46, 5.8, "Hercules Cluster (M13)", "gc"])

# ---- milky way outline (outermost contour, decimated) ----
mw_json = load("mw.json")
mw = []
for f in mw_json["features"]:
    if f["id"] not in ("ol1", "ol3"):
        continue
    polys = []
    for poly in f["geometry"]["coordinates"]:
        for ring in poly:
            step = max(1, len(ring) // 220)
            pts = []
            for lon, lat in ring[::step]:
                pts += [ra_from_lon(lon), round(lat, 1)]
            if len(pts) > 12:
                polys.append(pts)
    mw.append(polys)

data = {
    "stars": flat,
    "starNames": name_map,
    "starInfo": info_map,
    "cons": cons,
    "dsos": dsos,
    "mw": mw,
}

js = ("// Generated by build/make_data.py from d3-celestial data (BSD-3, ofrohn/d3-celestial),\n"
      "// itself derived from the HYG star database (Hipparcos). Do not edit by hand.\n"
      "var SKYDATA = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n"
      "if (typeof module !== 'undefined') module.exports = SKYDATA;\n")
with open(OUT, "w", encoding="utf-8") as f:
    f.write(js)

print(f"stars: {len(flat)//4}  named: {len(name_map)}  constellations: {len(cons)}"
      f"  dsos: {len(dsos)}  mw polys: {sum(len(m) for m in mw)}")
print(f"wrote {OUT}: {os.path.getsize(OUT)//1024} KB")
